const STATUS_TEXT = {
  passed: "Passed",
  failed: "Failed",
  ignored: "Ignored",
  terminated: "Terminated",
  skipped: "Skipped",
};

/** A report that opens in any browser: summary, then the tree with each test's status, duration and output. */
export function testResultsHtml(results: TestResults, info: TestExportInfo): string {
  const c = counts(results);
  const total = totalDuration(results);
  const title = `Test Results - ${info.name}`;
  const parts = [`<b>${c.total}</b> tests`, `<b>${c.passed}</b> passed`, `<b>${c.failed}</b> failed`];
  if (c.ignored > 0) parts.push(`<b>${c.ignored}</b> ignored`);
  if (total !== undefined) parts.push(escapeText(formatDuration(total)));
  const out = [
    "<!DOCTYPE html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    `<title>${escapeText(title)}</title>`,
    `<style>${STYLE}</style>`,
    "</head>",
    "<body>",
    `<h1>${escapeText(title)}</h1>`,
    `<p class="summary">${parts.join(" · ")}</p>`,
  ];
  const row = (node: TestNode, status: keyof typeof STATUS_TEXT) => {
    const d = nodeDuration(node);
    const where = locationText(node);
    return [
      `<span class="status">${STATUS_TEXT[status]}</span>`,
      `<span class="name">${escapeText(node.name)}</span>`,
      where ? `<span class="location">${escapeText(where)}</span>` : "",
      d !== undefined ? `<span class="duration">${escapeText(formatDuration(d))}</span>` : "",
    ].join("");
  };
  const visit = (nodes: readonly TestNode[]) => {
    out.push("<ul>");
    for (const n of nodes) {
      const status = statusOf(n);
      const output = n.output.length > 0 ? `<pre>${escapeText(n.output.join("\n"))}</pre>` : "";
      if (n.children.length === 0) {
        out.push(`<li><div class="test ${status}">${row(n, status)}</div>${output}</li>`);
        continue;
      }
      // Suites start open; a click on one folds it.
      out.push(`<li><details open class="${status}"><summary>${row(n, status)}</summary>${output}`);
      visit(n.children);
      out.push("</details></li>");
    }
    out.push("</ul>");
  };
  visit(results.roots);
  out.push(
    `<footer>Generated by OpenIDEA on ${escapeText(info.date.toLocaleString())}</footer>`,
    "</body>",
    "</html>",
    "",
  );
  return out.join("\n");
}

export function exportTestResults(format: TestExportFormat, results: TestResults, info: TestExportInfo): string {
  return format === "html" ? testResultsHtml(results, info) : testResultsXml(results, info);
}
