/**
 * IDEA's Export Test Results: the results tree as a self-contained HTML report,
 * or as XML in IDEA's `<testrun>` format (counts, suites, tests, output, diff).
 */
import { parseComparison } from "./comparison";
import { nodeDuration, nodeStatus, type TestNode, type TestResults } from "./results";
import { formatDuration } from "./types";

export type TestExportFormat = "html" | "xml";

export interface TestExportInfo {
  /** The run configuration's name. */
  name: string;
  /** Working directory: relative test locations are resolved against it. */
  cwd: string;
  date: Date;
}

/** Status words as IDEA writes them (`skipped` tests are `ignored`). */
function statusOf(node: TestNode): "passed" | "failed" | "ignored" | "terminated" | "skipped" {
  switch (nodeStatus(node)) {
    case "passed":
      return "passed";
    case "failed":
      return "failed";
    case "skipped":
      return "ignored";
    case "running":
      return "terminated";
    default:
      return "skipped";
  }
}

function totalDuration(results: TestResults): number | undefined {
  if (results.summary.durationMs !== undefined) return results.summary.durationMs;
  let sum: number | undefined;
  for (const r of results.roots) {
    const d = nodeDuration(r);
    if (d !== undefined) sum = (sum ?? 0) + d;
  }
  return sum;
}

export const isAbsolutePath = (path: string) => /^([a-zA-Z]:)?[\\/]/.test(path);

/** IDEA's `file://<path>:<line>` location of a test; only for locations that name a real path. */
function locationUrl(node: TestNode, cwd: string): string | undefined {
  const loc = node.location;
  if (!loc || loc.resolve !== "path") return undefined;
  const abs = isAbsolutePath(loc.path) ? loc.path : `${cwd.replace(/[\\/]+$/, "")}/${loc.path}`;
  return `file://${abs.replace(/\\/g, "/")}${loc.line !== undefined ? `:${loc.line}` : ""}`;
}

/** Where a test is, as the report shows it: `sub_test.go:9`. */
function locationText(node: TestNode): string | undefined {
  const loc = node.location;
  if (!loc) return undefined;
  const file = loc.path.split(/[\\/]/).pop() ?? loc.path;
  return loc.line !== undefined ? `${file}:${loc.line}` : file;
}

/** IDEA's importer reads durations as whole milliseconds. */
const ms = (d: number | undefined) => (d === undefined ? undefined : Math.round(d));

// XML 1.0 can't hold most control characters even escaped; test output may contain them.
// eslint-disable-next-line no-control-regex
const XML_INVALID = /[\u0000-\u0008\u000B\u000C\u000E-\u001F￾￿]/g;

function escapeXml(s: string): string {
  return s
    .replace(XML_INVALID, "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/\n/g, "&#10;")
    .replace(/\r/g, "&#13;")
    .replace(/\t/g, "&#9;");
}

/** Text content: line breaks stay as they are. */
const escapeText = (s: string) =>
  s.replace(XML_INVALID, "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function attrs(values: Record<string, string | number | undefined>): string {
  return Object.entries(values)
    .filter(([, v]) => v !== undefined)
    .map(([k, v]) => ` ${k}="${escapeXml(String(v))}"`)
    .join("");
}

function counts(results: TestResults) {
  const c = results.counts();
  return { total: c.total, passed: c.passed, failed: c.failed, ignored: c.skipped };
}

/** IDEA's export XML (`TestResultsXmlFormatter`): the same tags, so IDEA's Import Tests from File can read it. */
export function testResultsXml(results: TestResults, info: TestExportInfo): string {
  const out = ['<?xml version="1.0" encoding="UTF-8"?>'];
  out.push(
    `<testrun${attrs({
      duration: ms(totalDuration(results)),
      footerText: `Generated by OpenIDEA on ${info.date.toLocaleString()}`,
      name: info.name,
    })}>`,
  );
  for (const [name, value] of Object.entries(counts(results)))
    if (value > 0 || name === "total") out.push(`  <count${attrs({ name, value })}/>`);
  const visit = (node: TestNode, depth: number) => {
    const pad = "  ".repeat(depth);
    const tag = node.children.length > 0 ? "suite" : "test";
    const head = `${pad}<${tag}${attrs({
      locationUrl: locationUrl(node, info.cwd),
      name: node.name,
      status: statusOf(node),
      duration: ms(nodeDuration(node)),
    })}`;
    const comparison = tag === "test" && nodeStatus(node) === "failed" ? parseComparison(node.output) : null;
    if (node.children.length === 0 && node.output.length === 0 && !comparison) {
      out.push(`${head}/>`);
      return;
    }
    out.push(`${head}>`);
    if (comparison) out.push(`${pad}  <diff${attrs({ actual: comparison.actual, expected: comparison.expected })}/>`);
    if (node.output.length > 0)
      out.push(`${pad}  <output type="stdout">${escapeText(node.output.join("\n"))}</output>`);
    for (const c of node.children) visit(c, depth + 1);
    out.push(`${pad}</${tag}>`);
  };
  for (const r of results.roots) visit(r, 1);
  out.push("</testrun>", "");
  return out.join("\n");
}

