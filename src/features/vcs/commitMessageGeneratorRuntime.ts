/** Connects the commit panel to a sandboxed message provider without exposing credentials. */
import { invoke } from "@tauri-apps/api/core";
import type { IdeError } from "@/bindings";
import { editorsFor } from "@/editor/api";
import { commands, IpcError } from "@/platform/ipc";
import { tx } from "@/platform/i18n";
import { useProject } from "@/platform/project";
import { notifications } from "@/workbench/contributions";
import { withListDefaults, useChangelists } from "./changelists";
import { useCommit } from "./commitStore";
import { buildCommitDiff, limitCommitDiff, runCommitMessageGeneration } from "./commitMessageGenerator";
import { useVcs } from "./store";

/** Invoke a fallible Tauri command whose bindings are generated by the Rust build. */
async function invokeFallible<T>(command: string, args: Record<string, unknown>): Promise<T> {
  try {
    return await invoke<T>(command, args);
  } catch (error) {
    if (error && typeof error === "object" && "kind" in error && "message" in error)
      throw new IpcError(error as IdeError);
    throw error;
  }
}

/** Generates a draft for the current project's checked changes. */
export async function generateCommitMessage(pluginId: string): Promise<void> {
  const vcs = useVcs.getState();
  if (!useProject.getState().project || !vcs.root)
    throw new Error(tx("Open a project before generating a commit message"));
  const commit = useCommit.getState();
  const status = vcs.status.map((file) => ({ ...file }));
  const checks = withListDefaults(status, vcs.root, useChangelists.getState().state, commit.checks);
  const excludedHunks = new Map([...commit.excludedHunks].map(([path, keys]) => [path, new Set(keys)]));
  const roots = [...vcs.roots];
  let changes = 0;
  // A draft or inclusion change must invalidate an in-flight response even if restored later.
  const stopCommit = useCommit.subscribe((state, previous) => {
    if (
      state.message !== previous.message ||
      state.checks !== previous.checks ||
      state.excludedHunks !== previous.excludedHunks
    )
      changes++;
  });
  const stopProject = useProject.subscribe((state, previous) => {
    if (state.project?.root !== previous.project?.root) changes++;
  });
  const stopLists = useChangelists.subscribe((state, previous) => {
    if (state.state !== previous.state) changes++;
  });
  const stopVcs = useVcs.subscribe((state, previous) => {
    if (
      state.root !== previous.root ||
      JSON.stringify(state.roots) !== JSON.stringify(previous.roots) ||
      JSON.stringify(state.status) !== JSON.stringify(previous.status) ||
      JSON.stringify(state.heads) !== JSON.stringify(previous.heads)
    )
      changes++;
  });
  try {
    const outcome = await runCommitMessageGeneration({
      getState: () => ({
        project: useProject.getState().project?.root ?? null,
        message: useCommit.getState().message,
        changes,
      }),
      setMessage: (message) => useCommit.setState((state) => ({ message, focusTick: state.focusTick + 1 })),
      makeDiff: () => {
        const working = new Map<string, Promise<{ binary: boolean; text: string }>>();
        const revisions = new Map<string, Promise<{ binary: boolean; text: string }>>();
        const safeRevision = (path: string, rev: string) => {
          const key = `${path}\0${rev}`;
          let read = revisions.get(key);
          if (!read) {
            read = invokeFallible<{ binary: boolean; text: string }>("vcs_read_commit_revision", { path, rev });
            revisions.set(key, read);
          }
          return read;
        };
        const safeWorking = (path: string) => {
          let read = working.get(path);
          if (!read) {
            read = invokeFallible<{ binary: boolean; text: string }>("vcs_read_commit_working_file", { path }).then(
              (file) => {
                if (!file.binary && editorsFor(path).some((editor) => editor.view.state.doc.toString() !== file.text)) {
                  throw new Error(tx`Save ${path} before generating a commit message`);
                }
                return file;
              },
            );
            working.set(path, read);
          }
          return read;
        };
        return buildCommitDiff({
          status,
          checks,
          excludedHunks,
          roots,
          io: {
            isBinary: async (path, revision) =>
              revision === null ? (await safeWorking(path)).binary : (await safeRevision(path, revision)).binary,
            readRevision: async (path, revision) => (await safeRevision(path, revision)).text,
            readWorking: async (path) => (await safeWorking(path)).text,
            hunks: (oldText, newText) => commands.vcsDiffHunks(oldText, newText),
            patch: (path, oldText, newText, selected) =>
              invoke<string>("vcs_build_partial_patch", { path, oldText, newText, selected }),
          },
        });
      },
      generate: (diff) =>
        invokeFallible<string>("plugin_generate_commit_message", { pluginId, diff: limitCommitDiff(diff) }),
    });
    if (outcome === "changed") {
      notifications().notify({
        group: "vcs",
        level: "warning",
        title: tx("Commit changes or message changed"),
        body: tx("The generated message was not applied. Generate it again for the current selection."),
      });
    }
  } finally {
    stopCommit();
    stopProject();
    stopLists();
    stopVcs();
  }
}
