/**
 * Settings › Version Control › Confirmation: files created in the IDE are
 * added to Git (ask / silently / never); tracked files deleted in the IDE have
 * the deletion staged (`git rm`), with the same three choices.
 */
import { onFileOperation, type FileOperation } from "@/platform/fileOps";
import { call, commands, isTauri } from "@/platform/ipc";
import { loadSettings, useProject } from "@/platform/project";
import { workflowSettings } from "@/platform/workflowSettings";
import { ask } from "@/workbench/messages";
import { effectiveKind, relTo, stripSlash } from "./model";
import { runOp } from "./ops";
import { refreshNow, useVcs } from "./store";

const inside = (root: string, p: string) => p === root || p.startsWith(root.endsWith("/") ? root : root + "/");

/** Status paths affected by `paths` (a deleted folder covers its content). */
function matching(paths: readonly string[], kind: "untracked" | "deleted"): string[] {
  const out = new Set<string>();
  for (const f of useVcs.getState().status) {
    const p = stripSlash(f.path);
    if (effectiveKind(f) !== kind || f.staged) continue;
    for (const q of paths) {
      if (p === q || p.startsWith(q + "/")) out.add(p);
      // Inside an untracked folder git reports only the folder: add just the new path.
      else if (q.startsWith(p + "/")) out.add(q);
    }
  }
  return [...out];
}

/** Saves a "Don't ask again" answer to the global settings. */
export async function rememberSetting(key: string, value: unknown) {
  try {
    await call(commands.settingsSet("global", key, JSON.stringify(value)));
    await loadSettings();
  } catch {
    // keep asking
  }
}

async function confirmFiles(op: FileOperation["kind"], files: string[]): Promise<{ ok: boolean; remember: boolean }> {
  const root = useVcs.getState().root ?? "";
  const add = op === "created";
  const n = files.length;
  const what = n === 1 ? "file" : `${n} files`;
  const list = files
    .slice(0, 10)
    .map((f) => relTo(root, f))
    .join("\n");
  const r = await ask({
    title: add ? "Add File to Git" : "Remove File from Git",
    body: `${add ? `Do you want to add the following ${what} to Git?` : `Do you want to remove the following ${what} from Git?`}\n${list}${n > 10 ? "\n…" : ""}`,
    checkbox: "Don't ask again",
    width: 480,
    buttons: [{ id: "ok", label: add ? "Add" : "Remove", primary: true }],
  });
  return { ok: r.button === "ok", remember: r.checked };
}

/** Only assets in the open Unity project's Assets directory have paired metadata. */
function unityAssets(paths: readonly string[]): string[] {
  const project = useProject.getState().project;
  if (!project?.unity) return [];
  const assets = stripSlash(project.root) + "/Assets/";
  return paths.filter((p) => p.startsWith(assets) && !p.toLowerCase().endsWith(".meta"));
}

async function handle(op: FileOperation, current: () => boolean, added: (assets: string[]) => void) {
  const vcs = useVcs.getState();
  if (!vcs.available || !vcs.root || !isTauri()) return;
  const conf = workflowSettings().vcs.confirmation;
  const mode = op.kind === "created" ? conf.onCreate : conf.onDelete;
  if (mode === "never") return;
  const paths = op.paths.map(stripSlash).filter((p) => inside(vcs.root!, p));
  if (!paths.length) return;
  await refreshNow();
  if (!current()) return;
  const files = matching(paths, op.kind === "created" ? "untracked" : "deleted");
  if (!files.length) return;
  const assets = op.kind === "created" ? unityAssets(files) : [];
  const metas = new Set(assets.map((p) => p + ".meta"));
  // Include metadata already generated by Unity in the same confirmation.
  for (const f of useVcs.getState().status) {
    if (metas.has(f.path) && !f.staged && f.unstaged === "untracked") files.push(f.path);
  }
  if (mode === "ask") {
    const { ok, remember } = await confirmFiles(op.kind, files);
    if (remember) {
      const key = op.kind === "created" ? "vcs.confirmation.onCreate" : "vcs.confirmation.onDelete";
      await rememberSetting(key, ok ? "silently" : "never");
    }
    if (!ok) return;
  }
  if (!current()) return;
  const n = files.length;
  const ok = await runOp(
    op.kind === "created"
      ? `Add ${n} file${n === 1 ? "" : "s"} to Git`
      : `Remove ${n} file${n === 1 ? "" : "s"} from Git`,
    async () => {
      await call(commands.vcsStage([...new Set(files)]));
      return true;
    },
  );
  if (ok && assets.length && current()) {
    // Read status after staging, including metadata generated while the dialog was open.
    await refreshNow();
    if (current()) added(assets);
  }
}

export function installFileConfirmations(): () => void {
  // Consent belongs to these newly added assets, not every .meta the watcher sees.
  const pending = new Set<string>();
  let generation = 0;
  let disposed = false;
  let staging = false;
  const clear = () => {
    generation++;
    pending.clear();
  };
  const drain = () => {
    const vcs = useVcs.getState();
    if (disposed || staging || !pending.size || !vcs.available || !vcs.statusLoaded || vcs.loading || vcs.error) return;
    const status = new Map(vcs.status.map((f) => [stripSlash(f.path), f]));
    const files: string[] = [];
    for (const asset of pending) {
      const source = status.get(asset);
      const meta = status.get(asset + ".meta");
      // Unstaging/deleting the asset cancels the pending addition. Never re-stage
      // the asset itself: it may already have newer, intentionally unstaged edits.
      if (source?.staged !== "added" || source.unstaged === "deleted" || meta?.staged) {
        pending.delete(asset);
      } else if (meta?.unstaged === "untracked") {
        pending.delete(asset);
        files.push(meta.path);
      } else if (meta) {
        pending.delete(asset);
      }
    }
    if (!files.length) return;
    staging = true;
    // Remove before invoking to avoid repeated attempts on error or status refresh.
    void runOp("Add Unity metadata to Git", () => call(commands.vcsStage(files))).finally(() => {
      staging = false;
      drain();
    });
  };
  const stopVcs = useVcs.subscribe((s, prev) => {
    if (s.root !== prev.root || !s.available) clear();
    else if (s.version !== prev.version || s.status !== prev.status || s.loading !== prev.loading) drain();
  });
  const stopProject = useProject.subscribe((s, prev) => {
    if (s.project?.root !== prev.project?.root) clear();
  });
  const stopFiles = onFileOperation((op) => {
    const started = generation;
    void handle(
      op,
      () => !disposed && generation === started,
      (assets) => {
        for (const asset of assets) pending.add(asset);
        drain();
      },
    );
  });
  return () => {
    disposed = true;
    clear();
    stopFiles();
    stopVcs();
    stopProject();
  };
}
